RunFn = Callable[[list[str], dict[str, str], float], Awaitable[tuple[int, str, str]]]


async def _run_subprocess(cmd: list[str], env: dict[str, str], timeout_s: float) -> tuple[int, str, str]:
    """Run ``cmd`` to completion; return ``(returncode, stdout, stderr)``."""

    proc = await asyncio.create_subprocess_exec(
        *cmd, env=env, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
    )
    try:
        out, err = await asyncio.wait_for(proc.communicate(), timeout=timeout_s)
    except asyncio.TimeoutError:
        proc.kill()
        raise DeployError(
            f"`{' '.join(shlex.quote(c) for c in cmd[:3])} …` timed out after {int(timeout_s)}s",
            hint="Modal image builds can take several minutes the first time — "
            "retry, or raise opts.extra['deploy_timeout_s']",
            provider="modal",
        ) from None
    return proc.returncode or 0, out.decode("utf-8", "replace"), err.decode("utf-8", "replace")


_runner: RunFn = _run_subprocess


def _modal_toml_path() -> Path:
    return Path(os.environ.get("MODAL_CONFIG_PATH") or Path.home() / ".modal.toml")


def _toml_has_profile(path: Path) -> bool:
    """True when ``~/.modal.toml`` has any profile with a token pair. Parsed
    with tomllib/tomli when available, else a regex — never imports modal."""

    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return False
    try:
        try:
            import tomllib as _toml  # py>=3.11
        except ImportError:  # pragma: no cover - py<3.11
            import tomli as _toml  # type: ignore[no-redef]
        data = _toml.loads(text)
    except Exception:
        return bool(re.search(r"^\s*token_id\s*=", text, re.M) and re.search(r"^\s*token_secret\s*=", text, re.M))
    return any(
        isinstance(v, dict) and v.get("token_id") and v.get("token_secret") for v in data.values()
    )


def _modal_installed() -> bool:
    """Is the ``modal`` SDK importable? Cheap and offline — the provider cards
    ask this so a missing package is visible before anyone picks a GPU, rather
    than surfacing as a failed deploy."""
    from importlib.util import find_spec  # noqa: PLC0415

    try:
        return find_spec("modal") is not None
    except (ImportError, ValueError):  # pragma: no cover - broken meta path
        return False


def _import_modal() -> Any:
    try:
        import modal  # noqa: PLC0415
    except ImportError:
        raise DeployError(
            "the `modal` package is not installed",
            hint="pip install mantis-agent-sdk[modal]",
            provider="modal",
        ) from None
    return modal


def _parse_json_line(stdout: str) -> dict[str, Any] | None:
    for line in reversed(stdout.strip().splitlines()):
        line = line.strip()
        if line.startswith("{") and line.endswith("}"):
            try:
                return json.loads(line)
            except ValueError:
                continue
    return None


