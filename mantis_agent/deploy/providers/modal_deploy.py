def _image_expr(engine: Engine, opts: DeployOpts) -> str:
    version = (opts.engine_version or DEFAULT_VLLM_VERSION).lstrip("v")
    if engine == "vllm":
        pkg = f"vllm=={version}"
    elif engine == "sglang":
        pkg = f"sglang[all]=={opts.engine_version}" if opts.engine_version else "sglang[all]"
    else:
        raise NotSupported(
            f"Modal adapter supports vllm and sglang, not {engine!r}",
            hint="pick engine='vllm' (default) or 'sglang'",
            provider="modal",
        )
    return (
        'modal.Image.from_registry("nvidia/cuda:12.9.0-devel-ubuntu22.04", add_python="3.12")\n'
        "    .entrypoint([])\n"
        f"    .uv_pip_install({pkg!r})\n"
        '    .env({"HF_XET_HIGH_PERFORMANCE": "1"})'
    )


def _command_expr(model: str, engine: Engine, opts: DeployOpts, *, with_api_key: bool) -> str:
    """The Popen argv as Python source. ``--api-key`` reads ``VLLM_API_KEY``
    from the container env (the secret) so the key is never in the file."""

    flags = build_engine_args(model, engine, opts, api_key=None, port=PORT)
    # Multi-GPU on Modal: --tensor-parallel-size follows the gpu count unless the user pinned it.
    head = ["vllm", "serve", model] if engine == "vllm" else [
        "python", "-m", "sglang.launch_server", "--model-path", model,
    ]
    parts = [repr(a) for a in head + flags]
    if with_api_key:
        parts += ['"--api-key"', 'os.environ["VLLM_API_KEY"]']
    return "[\n            " + ",\n            ".join(parts) + ",\n        ]"


def render_modal_app(
    *,
    app_name: str,
    model: str,
    engine: Engine,
    gpu: str,
    gpu_count: int,
    opts: DeployOpts,
    filename: str,
    has_hf_token: bool,
    unauthenticated: bool,
) -> str:
    """Render the Modal app module. Pure function — tests assert on the text."""

    secret_keys: list[str] = []
    if has_hf_token:
        secret_keys.append("HF_TOKEN")
    if unauthenticated:
        secret_keys.append("VLLM_API_KEY")
    if secret_keys:
        pairs = ", ".join(f'{k!r}: os.environ[{("MANTIS_" + k)!r}]' for k in secret_keys)
        secrets_block = f"SECRETS = [modal.Secret.from_dict({{{pairs}}})]"
    else:
        secrets_block = "SECRETS = []"

    return _TEMPLATE.format(
        model=model,
        engine=engine,
        gpu=gpu,
        gpu_count=gpu_count,
        filename=filename,
        app_name=app_name,
        port=PORT,
        image_expr=_image_expr(engine, opts),
        secrets_block=secrets_block,
        scaledown_window=int(opts.idle_timeout_s),
        startup_timeout=600,
        min_containers=int(opts.min_replicas),
        max_containers=max(1, int(opts.max_replicas)),
        engine_cache_mount="/root/.cache/vllm" if engine == "vllm" else "/root/.cache/sglang",
        target_concurrency=int(opts.extra.get("target_concurrency", 100)),
        unauthenticated=bool(unauthenticated),
        command_expr=_command_expr(model, engine, opts, with_api_key=unauthenticated),
    )


