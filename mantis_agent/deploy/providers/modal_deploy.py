"""Modal deploy adapter — render a ``@app.server`` vLLM/SGLang app and deploy it.

Modal has no REST control plane: everything is the Python SDK over gRPC,
and ``App.deploy()`` must run on an ``App`` object built in the current
process. So this adapter

1. renders a self-contained Python module from :data:`_TEMPLATE` into
   ``~/.mantis-agent/deploy/modal/<slug>.py`` (no secrets in the file —
   the HF token and the generated inference key reach it through the
   subprocess env and end up in a ``modal.Secret.from_dict``),
2. runs it in a **subprocess** (``python <file>``) with the tokens in env,
   so an SDK crash, a gRPC hang or a ``sys.exit`` inside Modal can't take
   the dashboard/terminal down; the module prints one JSON line
   ``{"url": Server.get_url(), "app": name}`` which we parse,
3. shells out to the ``modal`` CLI (``python -m modal …``) for the things
   the SDK doesn't expose as plain Python: ``app list --json``,
   ``app logs``, ``app stop``.

Endpoint auth (what the SDK sends on inference calls)
-----------------------------------------------------
Modal Servers require *proxy auth* by default: ``Modal-Key`` +
``Modal-Secret`` headers carrying a **workspace proxy token** (created in
the dashboard or ``modal workspace proxy-tokens create``). We record those
as env refs (``${MODAL_PROXY_TOKEN_ID}`` / ``${MODAL_PROXY_TOKEN_SECRET}``)
in ``Deployment.auth_headers`` — the same header pair
:class:`mantis_agent.providers.modal_provider.ModalProvider` sends.

When no proxy token is configured (or ``opts.extra["unauthenticated"]`` is
True) we deploy with ``unauthenticated=True`` and hand vLLM/SGLang a
generated ``--api-key`` instead; the key lives in
``os.environ[MANTIS_DEPLOY_<SLUG>_KEY]`` and only the env *name* is
persisted (``Deployment.auth_env``, Bearer on inference calls).
"""

