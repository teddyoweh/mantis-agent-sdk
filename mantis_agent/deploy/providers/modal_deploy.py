@register_provider
class ModalDeployProvider:
    id = "modal"
    display_name = "Modal"
    credential_fields = (
        CredentialField("MODAL_TOKEN_ID", "Modal token id", secret=True, required=True,
                        help="modal.com → Settings → API Tokens (or `modal token new`)"),
        CredentialField("MODAL_TOKEN_SECRET", "Modal token secret", secret=True, required=True,
                        help="shown once when the token is created"),
        CredentialField("MODAL_PROXY_TOKEN_ID", "Proxy auth token id", secret=True, required=False,
                        help="modal.com → Settings → Proxy Auth Tokens; without one the endpoint "
                        "is deployed unauthenticated behind a generated vLLM --api-key"),
        CredentialField("MODAL_PROXY_TOKEN_SECRET", "Proxy auth token secret", secret=True, required=False),
        CredentialField("HF_TOKEN", "Hugging Face token", secret=True, required=False,
                        help="only for gated repos; stored as a modal.Secret on the app"),
    )
    engines: tuple[Engine, ...] = ("vllm", "sglang")
    console_url = "https://modal.com/apps"
    scale_to_zero = True
    public_by_default = False

    # ----- credentials ---------------------------------------------------

    def configured(self) -> bool:
        if os.environ.get("MODAL_TOKEN_ID") and os.environ.get("MODAL_TOKEN_SECRET"):
            return True
        return _toml_has_profile(_modal_toml_path())

    def requirements(self) -> tuple[bool, str]:
        """Modal deploys by running its own SDK, so the package has to be here.
        Reported alongside ``configured()`` so the UI can say "needs the modal
        package" up front instead of failing the deploy at zero seconds."""
        if _modal_installed():
            return True, ""
        return False, "the `modal` package is not installed — pip install mantis-agent-sdk[modal]"

    def _env(self) -> dict[str, str]:
        env = dict(os.environ)
        env.setdefault("MODAL_AUTOMOUNT", "0")
        return env

    async def _cli(self, args: list[str], *, timeout_s: float = 120.0) -> str:
        _import_modal()
        cmd = [sys.executable, "-m", "modal", *args]
        rc, out, err = await _runner(cmd, self._env(), timeout_s)
        if rc != 0:
            msg = (err or out).strip().splitlines()
            tail = msg[-1] if msg else f"exit {rc}"
            if "token" in tail.lower() or "auth" in tail.lower() or "credential" in tail.lower():
                hint = "check MODAL_TOKEN_ID / MODAL_TOKEN_SECRET (modal.com → Settings → API Tokens)"
            else:
                hint = f"run `modal {' '.join(args)}` yourself to see the full error"
            raise DeployError(f"modal {args[0]} failed: {tail}", hint=hint, provider="modal")
        return out

    async def validate_credentials(self) -> Account:
        if not self.configured():
            return Account(ok=False, provider=self.id, message="MODAL_TOKEN_ID / MODAL_TOKEN_SECRET not set")
        out = await self._cli(["app", "list", "--json"])
        apps = self._parse_app_list(out)
        ours = [a for a in apps if a.get("name", "").startswith(APP_PREFIX)]
        return Account(
            ok=True, provider=self.id,
            message=f"{len(apps)} app(s) visible, {len(ours)} deployed by mantis",
        )

    # ----- catalogue -----------------------------------------------------

    async def list_gpus(self) -> list[GpuSpec]:
        rows: list[GpuSpec] = []
        for family, modal_id, vram, price in MODAL_GPUS:
            for n in range(1, _MAX_GPU_COUNT + 1):
                pid = modal_id if n == 1 else f"{modal_id}:{n}"
                rows.append(GpuSpec(
                    provider_id=pid, family=family, vram_gb=vram, count=n,
                    price_per_hour=round(price * n, 2), available=True, region=None,
                    label=f"{modal_id} ×{n} ({vram} GB)" if n > 1 else f"{modal_id} ({vram} GB)",
                ))
        rows.sort(key=lambda g: (g.price_per_hour or 0.0, g.count))
        return rows

    # ----- deploy --------------------------------------------------------

    @staticmethod
    def _gpu_string(gpu: GpuSpec) -> tuple[str, int]:
        base = gpu.provider_id.split(":", 1)[0]
        count = max(1, gpu.count)
        if ":" in gpu.provider_id:
            try:
                count = int(gpu.provider_id.split(":", 1)[1])
            except ValueError:
                pass
        return (f"{base}:{count}" if count > 1 else base), count

    def _proxy_token_configured(self) -> bool:
        return bool(os.environ.get("MODAL_PROXY_TOKEN_ID") and os.environ.get("MODAL_PROXY_TOKEN_SECRET"))

    async def deploy(self, model: str, gpu: GpuSpec, engine: Engine, opts: DeployOpts) -> Deployment:
        if engine not in self.engines:
            raise NotSupported(
                f"Modal adapter supports vllm and sglang, not {engine!r}",
                hint="pick engine='vllm' (default) or 'sglang'", provider=self.id,
            )
        _import_modal()
        if not self.configured():
            raise DeployError(
                "Modal credentials missing",
                hint="set MODAL_TOKEN_ID and MODAL_TOKEN_SECRET (modal.com → Settings → API Tokens)",
                provider=self.id,
            )

        slug = slugify(opts.name or model)
        app_name = APP_PREFIX + slug
        gpu_str, gpu_count = self._gpu_string(gpu)
        if opts.tensor_parallel is None:
            opts.tensor_parallel = gpu_count

        hf_token = opts.hf_token or os.environ.get("HF_TOKEN")
        unauthenticated = bool(opts.extra.get("unauthenticated")) or not self._proxy_token_configured()

        from ...paths import get_mantis_agent_dir  # noqa: PLC0415

        out_dir = get_mantis_agent_dir() / "deploy" / "modal"
        out_dir.mkdir(parents=True, exist_ok=True)
        path = out_dir / f"{slug}.py"
        source = render_modal_app(
            app_name=app_name, model=model, engine=engine, gpu=gpu_str, gpu_count=gpu_count,
            opts=opts, filename=path.name, has_hf_token=bool(hf_token), unauthenticated=unauthenticated,
        )
        path.write_text(source, encoding="utf-8")

        env = self._env()
        auth_env: str | None = None
        auth_headers: dict[str, str] = {}
        if hf_token:
            env["MANTIS_HF_TOKEN"] = hf_token
        if unauthenticated:
            auth_env = auth_env_name(slug)
            key = os.environ.get(auth_env) or generate_api_key()
            os.environ[auth_env] = key      # the store persists the NAME only
            env["MANTIS_VLLM_API_KEY"] = key
        else:
            auth_headers = {
                "Modal-Key": "${MODAL_PROXY_TOKEN_ID}",
                "Modal-Secret": "${MODAL_PROXY_TOKEN_SECRET}",
            }

        timeout_s = float(opts.extra.get("deploy_timeout_s", 900))
        rc, stdout, stderr = await _runner([sys.executable, str(path)], env, timeout_s)
        result = _parse_json_line(stdout)
        if rc != 0 or not result or not result.get("url"):
            tail = "\n".join((stderr or stdout).strip().splitlines()[-8:])
            raise DeployError(
                f"modal deploy of {app_name} failed (exit {rc})",
                hint=f"run `python {path}` to see the full error\n{tail}".rstrip(),
                provider=self.id,
            )
        url = str(result["url"]).rstrip("/")
        msg = (
            f"deployed {app_name}; endpoint auth = generated key in ${auth_env} (unauthenticated Modal server)"
            if unauthenticated else
            f"deployed {app_name}; endpoint auth = Modal proxy token (Modal-Key/Modal-Secret)"
        )
        return Deployment(
            id=app_name, provider=self.id, model=model, engine=engine, status="starting",
            gpu=gpu, served_model_name=opts.served_model_name or model,
            endpoint_url=url + "/v1", name=app_name, opts=opts,
            auth_env=auth_env, auth_headers=auth_headers, message=msg,
            raw={"app": result.get("app", app_name), "module": str(path), "gpu": gpu_str,
                 "unauthenticated": unauthenticated},
        )

    # ----- status ----------------------------------------------------------

    def _inference_headers(self, dep: Deployment) -> dict[str, str]:
        headers = resolve_env_refs(dep.auth_headers)
        if dep.auth_env and os.environ.get(dep.auth_env):
            headers["Authorization"] = f"Bearer {os.environ[dep.auth_env]}"
        return headers

    async def status(self, dep: Deployment) -> Deployment:
        if not dep.endpoint_url:
            dep.status = "unknown"
            dep.message = "no endpoint URL recorded"
            return dep
        base = dep.endpoint_url.rstrip("/")
        if base.endswith("/v1"):
            base = base[:-3]
        try:
            async with httpx.AsyncClient(timeout=httpx.Timeout(20.0, connect=10.0)) as client:
                r = await client.get(f"{base}/health", headers=self._inference_headers(dep))
        except httpx.HTTPError as e:
            dep.status = "unknown"
            dep.message = f"health check failed: {type(e).__name__}"
            return dep
        if r.status_code == 200:
            dep.status, dep.message = "running", "healthy"
        elif r.status_code == 503:
            dep.status = "scaled_to_zero" if dep.opts.min_replicas == 0 else "starting"
            dep.message = "cold start: Modal is spinning up a container (503)"
        elif r.status_code in (401, 403):
            dep.status = "unknown"
            dep.message = (
                f"endpoint returned {r.status_code}: proxy auth rejected — "
                "check MODAL_PROXY_TOKEN_ID / MODAL_PROXY_TOKEN_SECRET"
            )
        elif r.status_code == 404:
            dep.status, dep.message = "deleted", "endpoint returned 404 (app stopped?)"
        else:
            dep.status, dep.message = "unknown", f"health returned {r.status_code}"
        return dep

    async def wait_ready(self, dep: Deployment, timeout_s: int = 1200) -> Deployment:
        deadline = _boot._clock() + timeout_s
        delay = 3.0
        while True:
            dep = await self.status(dep)
            if dep.status == "running":
                return dep
            if dep.status in ("failed", "deleted"):
                raise DeployError(f"deployment {dep.id} is {dep.status}: {dep.message}", provider=self.id)
            if _boot._clock() >= deadline:
                raise DeployError(
                    f"{dep.id} not ready after {timeout_s}s ({dep.message})",
                    hint=f"`modal app logs {dep.id}` — first boot downloads the weights into the cache Volume",
                    provider=self.id,
                )
            await _http.sleep(min(delay, max(0.0, deadline - _boot._clock())))
            delay = min(delay * 1.6, 15.0)

    # ----- logs / list / delete / cost -------------------------------------

    async def logs(self, dep: Deployment, tail: int = 200) -> AsyncIterator[str]:
        out = await self._cli(["app", "logs", dep.id, "-n", str(tail)], timeout_s=60.0)
        lines = out.splitlines()
        for line in lines[-tail:] if tail > 0 else lines:
            yield line

    @staticmethod
    def _parse_app_list(out: str) -> list[dict[str, Any]]:
        try:
            data = json.loads(out or "[]")
        except ValueError:
            raise DeployError("could not parse `modal app list --json` output", provider="modal") from None
        if isinstance(data, dict):
            data = data.get("apps") or data.get("items") or []
        rows: list[dict[str, Any]] = []
        for a in data if isinstance(data, list) else []:
            if not isinstance(a, dict):
                continue
            name = a.get("Description") or a.get("Name") or a.get("name") or a.get("description") or ""
            rows.append({
                "name": str(name),
                "app_id": a.get("App ID") or a.get("app_id") or a.get("id"),
                "state": str(a.get("State") or a.get("state") or "").lower(),
                "created_at": a.get("Created at") or a.get("created_at"),
                "raw": a,
            })
        return rows

    async def list_deployments(self) -> list[Deployment]:
        out = await self._cli(["app", "list", "--json"])
        deps: list[Deployment] = []
        for a in self._parse_app_list(out):
            if not a["name"].startswith(APP_PREFIX):
                continue
            state = a["state"]
            status = "running" if state == "deployed" else "deleted" if state == "stopped" else "unknown"
            deps.append(Deployment(
                id=a["name"], provider=self.id, model=a["name"][len(APP_PREFIX):], engine="vllm",
                status=status,  # type: ignore[arg-type]
                gpu=GpuSpec(provider_id="unknown", family="other", vram_gb=0),
                served_model_name=a["name"][len(APP_PREFIX):], name=a["name"],
                message=f"modal state: {state or 'unknown'}",
                raw={"app_id": a["app_id"], "list": a["raw"]},
            ))
        return deps

    async def delete(self, dep: Deployment) -> None:
        try:
            await self._cli(["app", "stop", dep.id, "-y"])
        except DeployError as e:
            if "not found" in str(e).lower() or "no such" in str(e).lower():
                return
            raise
        if dep.auth_env:
            os.environ.pop(dep.auth_env, None)

    async def cost(self, dep: Deployment) -> CostEstimate:
        price = dep.gpu.price_per_hour
        if price is None:
            price = next(
                (p * max(1, dep.gpu.count) for fam, mid, _v, p in MODAL_GPUS if fam == dep.gpu.family), None,
            )
        maxr = max(1, dep.opts.max_replicas)
        minr = max(0, dep.opts.min_replicas)
